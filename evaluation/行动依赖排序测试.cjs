const fs=require('node:fs'), vm=require('node:vm'), assert=require('node:assert/strict');
const html=fs.readFileSync(require('node:path').join(__dirname,'../prototype.html'),'utf8');
const helpers=html.slice(html.indexOf('function dependencyError('),html.indexOf('let pointerSort='));
const change=html.slice(html.indexOf('function changeTask('),html.indexOf('function cancelTaskForm('));
const task=(id,group,order)=>({id,title:id,issueId:group,order,status:'待办',dependsOn:[],required:true});
const p={id:'问题',status:'待处理'}, db={tasks:[task('甲','问题',0),task('乙','问题',1),task('丙','问题',2),task('独立',null,0)]};
let lastToast='',saved=0;
const ctx=vm.createContext({db,issue:id=>id==='问题'?p:null,log:()=>{},toast:s=>lastToast=s,changed:()=>saved++,$:()=>({open:false}),remaining:()=>[],setState:(p,s)=>p.status=s,transitionIssue:(p)=>{p.status='处理中';return ''}});
vm.runInContext(helpers+change,ctx);
const [a,b,c]=db.tasks;
assert.equal(ctx.setTaskDependencies('乙',['甲']), '');
assert.equal(ctx.blockedBy(b).length,1);
ctx.changeTask(b,'advance');
assert.equal(b.status,'待办');
assert.equal(p.status,'待处理'); // A blocked attempt must not advance the issue.
assert.equal(saved,0);
assert.ok(lastToast.includes('前置'));
assert.ok(ctx.setTaskDependencies('甲',['乙']).includes('循环'));
assert.deepEqual(a.dependsOn,[]);
assert.ok(ctx.setTaskDependencies('丙',['丙']).includes('自己'));
assert.ok(ctx.setTaskDependencies('独立',['甲']).includes('同一个'));
assert.ok(ctx.setTaskDependencies('丙',['不存在']).includes('同一个'));
a.status='已完成';
assert.equal(ctx.blockedBy(b).length,0);
ctx.changeTask(b,'advance');
assert.equal(b.status,'进行中');
assert.equal(p.status,'处理中');
assert.ok(ctx.setTaskDependencies('乙',['丙']).includes('退回'));
assert.equal(b.dependsOn[0],'甲');
ctx.changeTask(a,'toggle');
assert.equal(a.status,'已完成'); // Active dependents prevent reopening prerequisites.
ctx.changeTask(b,'advance');
assert.equal(b.status,'待办');
ctx.changeTask(a,'toggle');
assert.equal(a.status,'待办');
a.status='已取消';
assert.equal(ctx.blockedBy(b).length,1); // Cancelled is not completed.
ctx.changeTask(b,'toggle');
assert.equal(b.status,'待办');
assert.equal(ctx.reorderTask('丙','甲',false),true);
assert.deepEqual(db.tasks.filter(t=>t.issueId==='问题').sort((a,b)=>a.order-b.order).map(t=>t.id),['丙','甲','乙']);
assert.equal(b.dependsOn[0],'甲');
assert.equal(ctx.reorderTask('甲','乙',true),true);
assert.deepEqual(db.tasks.filter(t=>t.issueId==='问题').sort((a,b)=>a.order-b.order).map(t=>t.id),['丙','乙','甲']);
assert.equal(ctx.reorderTask('甲','独立'),false);
const refreshed=JSON.parse(JSON.stringify(db));
assert.equal(refreshed.tasks.find(t=>t.id==='乙').dependsOn[0],'甲');
assert.equal(refreshed.tasks.find(t=>t.id==='甲').order,2);
assert.equal(ctx.setTaskDependencies('乙',[]),'');
assert.equal(ctx.blockedBy(b).length,0);
assert.equal(ctx.dependencyError([{id:'1',issueId:'x',dependsOn:['2']},{id:'2',issueId:'x',dependsOn:['3']},{id:'3',issueId:'x',dependsOn:[]}],'3',['1']).includes('循环'),true);
ctx.OPEN_STATES=['待梳理','待处理','处理中','待验证'];
ctx.linked=id=>db.tasks.filter(t=>t.issueId===id);
vm.runInContext(html.slice(html.indexOf('function transitionIssue('),html.indexOf('function taskHTML(')),ctx);
db.tasks=[task('前置','问题',0),task('后续','问题',1)];
db.tasks[0].status='已完成';db.tasks[1].dependsOn=['前置'];p.status='处理中';
const closeValues={reason:'验证关闭',closeType:'不再处理',taskPolicy:'detach'};
assert.ok(ctx.transitionIssue(p,'close-issue',closeValues).includes('依赖'));
assert.equal(db.tasks[1].issueId,'问题');
assert.equal(p.status,'处理中');
closeValues.taskPolicy='cancel';
assert.equal(ctx.transitionIssue(p,'close-issue',closeValues),'');
assert.equal(db.tasks[1].status,'已取消');
assert.equal(db.tasks[1].dependsOn[0],'前置');
console.log('行动依赖与排序测试通过：循环/跨组/自身校验、开始与完成阻塞、取消前置、后续保护、拖动算法、持久化及依赖移除。');
