const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(require('node:path').join(__dirname, '../prototype.html'), 'utf8');
const normalize = html.slice(html.indexOf('function normalizeData('), html.indexOf('\nfunction log('));
const ctx = vm.createContext({ ISSUE_STATES: ['待梳理','待处理','处理中','待验证','已解决','已暂缓','已关闭'], numberingMigrated: false });
vm.runInContext(normalize, ctx);
const row = (id, number) => ({id, number, title:id, status:'待梳理'});
const data = {version:1, issues:[row('甲'),row('乙')], tasks:[{id:'行动',title:'关联',status:'待办',issueId:'甲'}]};
ctx.normalizeData(data);
assert.equal(data.issues[0].number, 1);
assert.equal(data.issues[1].number, 2);
assert.equal(data.tasks[0].issueId, '甲');
assert.equal(data.nextIssueNumber, 3);
data.issues.reverse();
data.issues[0].title = '修改标题';
data.issues[0].status = '已关闭';
ctx.normalizeData(data);
assert.equal(data.issues.find(p=>p.id==='甲').number, 1);
assert.equal(data.issues.find(p=>p.id==='乙').number, 2);
data.issues.unshift(row('丙'));
ctx.normalizeData(data);
assert.equal(data.issues[0].number, 3);
const refreshed = JSON.parse(JSON.stringify(data));
ctx.normalizeData(refreshed);
assert.equal(JSON.stringify(refreshed), JSON.stringify(data));
data.issues = data.issues.filter(p=>p.id!=='丙');
data.issues.unshift(row('丁'));
ctx.normalizeData(data);
assert.equal(data.issues[0].number, 4);
data.issues.push(row('重复', 1));
ctx.normalizeData(data);
assert.equal(new Set(data.issues.map(p=>p.number)).size, data.issues.length);
assert.equal(data.issues.find(p=>p.id==='甲').number, 1);
data.issues.push(row('大编号', 10000), row('新记录'));
ctx.normalizeData(data);
assert.equal(data.issues.at(-1).number, 10001);
console.log('12项问题编号断言通过：旧数据迁移、关联保持、排序/标题/状态稳定、新增递增、刷新、删除不复用、重复修复与大编号。');
